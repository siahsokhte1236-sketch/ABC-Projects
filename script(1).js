  function openSim(id) {
    currentSim = id; currentPhet = -1;
    frameWrap.style.display = "none";
    frame.src = "about:blank";
    cvWrap.style.display = "block";
    cv.onpointerdown = null; cv.onpointermove = null; cv.onpointerup = null;
    resizeCv();
    var sel = panel.querySelector('[data-sim="' + id + '"]');
    setActiveExp(sel);
    var meta = null;
    for (var i = 0; i < SIMS.length; i++) if (SIMS[i].id === id) meta = SIMS[i];
    hintEl.textContent = meta ? meta.icon + " " + meta.name : "";
    document.getElementById("phyCtlTitle").textContent = "🎛️ کنترل‌ها";
    if (id === "projectile") { ctlProjectile(); startLoop(stepProjectile); }
    else if (id === "pendulum") { ctlPendulum(); startLoop(stepPendulum); }
    else if (id === "refraction") { ctlRefraction(); startLoop(stepRefraction); }
  }

