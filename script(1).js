  function startLoop(step) {
    stopLoop();
    activeStep = step;
    lastT = performance.now();
    (function tick(now) {
      if (!phyOpen) return;
      animId = requestAnimationFrame(tick);
      var dt = Math.min((now - lastT) / 1000, 0.05);
      lastT = now;
      if (activeStep) activeStep(dt);
    })(lastT);
  }
